import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
REALISTIC = REPO_ROOT / "tests" / "realistic"
MANIFEST_PATH = REALISTIC / "codex-y5-manifest.json"
RUN_LIVE_PIN_COMMIT = "1e3901c"
EXPECTED_FILES = 27

# (manifest path, repo-relative source). run_live.py comes from the
# pinned commit, not the working tree (see the module docstring).
