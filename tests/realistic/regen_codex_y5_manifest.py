#!/usr/bin/env python3
"""Regenerate tests/realistic/codex-y5-manifest.json from the ship
bytes (Y13f F1: the Council A ship-time guard).

The original failure mode (7923877): a runner edit after the regen
left a stale manifest committed, and the only thing standing between
that commit and a refused launch was a human remembering to re-run
the regen by hand. This script owns the file list and the
1e3901c run_live.py pin, so the manifest is regenerated by script,
not by hand, after any runner edit.

Usage (from the repo root):
  python3 tests/realistic/regen_codex_y5_manifest.py
  python3 tests/realistic/regen_codex_y5_manifest.py --stage DIR

Default: recompute the md5s from the working tree (run_live.py
from `git show 1e3901c:tests/realistic/run_live.py`, everything
else from the working tree) and rewrite codex-y5-manifest.json.
Prints the manifest md5 and the entry count; exits 2 unless the
count is exactly 27.

--stage DIR: also assemble the ship dir (curated copy of the 27
files: run_live.py from 1e3901c, everything else from the working
tree, plus the freshly written manifest), delete any __pycache__
in it, and run --verify-manifest on the staged runner. The staged
ship is then exactly the bytes the manifest describes. The
manifest must be committed + pushed before the launcher will
accept a ship staged from it (the launcher compares the ship
manifest md5 against the COMMITTED manifest from git).

Deletes tests/realistic/__pycache__ first: a stale .pyc there is
dead weight (no import of the runner works anymore: the
script-form-only guard exits 2 on any import, so the deletion is
hygiene for probes and staging, not for "the next module import").

Script form only (Y13g B1/B4): the staged verify runs as
`python3 -P run_codex_y5.py --verify-manifest` (PYTHONSAFEPATH=1).
-m and bare imports are unsupported invocation forms; the runner
and the launcher both refuse them at the module top (exit 2).
"""

