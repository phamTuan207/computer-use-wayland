def _md5(data):
    return hashlib.md5(data).hexdigest()


def _pinned_run_live_bytes():
    show = subprocess.run(
        ["git", "-C", str(REPO_ROOT), "show",
         f"{RUN_LIVE_PIN_COMMIT}:tests/realistic/run_live.py"],
        capture_output=True, timeout=60)
    if show.returncode != 0:
        print(f"git show of pinned run_live.py failed: "
              f"{show.stderr.decode('utf-8', 'replace').strip()[:200]}",
              file=sys.stderr)
        sys.exit(2)
    return show.stdout


def build_entries():
    entries = []
    for manifest_path, source in MANIFEST_SOURCES:
        if source is None:
            data = _pinned_run_live_bytes()
        else:
            data = (REPO_ROOT / source).read_bytes()
        entries.append({"path": manifest_path, "md5": _md5(data)})
    return entries


def regen():
    cache = REALISTIC / "__pycache__"
    if cache.is_dir():
        shutil.rmtree(cache)
        print(f"removed stale {cache}")
    entries = build_entries()
    if len(entries) != EXPECTED_FILES:
        print(f"entry count {len(entries)}, want {EXPECTED_FILES}",
              file=sys.stderr)
        return 2
    MANIFEST_PATH.write_text(
        json.dumps({"files": entries}, indent=2) + "\n")
    md5 = _md5(MANIFEST_PATH.read_bytes())
    print(f"wrote {MANIFEST_PATH} ({len(entries)} files, "
          f"manifest md5 {md5})")
    return 0


def stage(dest):
    dest = Path(dest)
    if regen() != 0:
        return 2
    if dest.exists():
        shutil.rmtree(dest)
    for manifest_path, source in MANIFEST_SOURCES:
        target = dest / manifest_path
        target.parent.mkdir(parents=True, exist_ok=True)
        if source is None:
            target.write_bytes(_pinned_run_live_bytes())
        else:
            shutil.copy2(REPO_ROOT / source, target)
    shutil.copy2(MANIFEST_PATH, dest / "codex-y5-manifest.json")
    shutil.copy2(REALISTIC / "codex-y5" / "SHIPPED.md",
                 dest / "codex-y5" / "SHIPPED.md")
    # Ship-time __pycache__ deletion (Y13f H1): a staged ship must
    # contain no bytecode at all.
    for cache in dest.rglob("__pycache__"):
        shutil.rmtree(cache)
        print(f"removed staged {cache}")
    print(f"staged ship at {dest}")
    proc = subprocess.run(
        ["python3", "-P", "run_codex_y5.py", "--verify-manifest"],
        cwd=str(dest), capture_output=True, text=True, timeout=120)
    print(proc.stdout.strip())
    print(proc.stderr.strip(), file=sys.stderr)
    print(f"--verify-manifest exit {proc.returncode}")
    return proc.returncode


def main(argv):
    if len(argv) == 3 and argv[1] == "--stage":
        return stage(argv[2])
    if len(argv) == 1:
        return regen()
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
